function format(template, params) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    params[key] !== undefined ? String(params[key]) : match
  );
}

export function createTranslator(locale) {
  const ui = UI[locale] ?? UI.en;
  const core = CORE[locale] ?? CORE.en;
  const t = (key, params) =>
    format(ui[key] ?? core[key] ?? UI.en[key] ?? CORE.en[key] ?? key, params);
  // BCP 47 tag for Intl formatters (zh_TW -> zh-TW).
  t.locale = locale.replace('_', '-');
  return t;
}

export const I18nContext = createContext(createTranslator('en'));

export function useT() {
  return useContext(I18nContext);
}
